import pandas as pd

# Create raw dataset
data = {
    "Name": ["Alice", "Bob", "Charlie", "Alice", "David", "Eva"],
    "Age": [25, 30, 28, 25, None, 35],
    "Salary": [35000, 45000, 40000, 35000, 30000, -1000],
    "Department": ["Sales", "IT", "HR", "Sales", "IT", "HR"]
}

pd.DataFrame(data).to_csv("raw_dataset.csv", index=False)

# Read CSV file
df = pd.read_csv("raw_dataset.csv")

print("Original Data:")
print(df)

# Remove duplicate records
df = df.drop_duplicates()

# Handle missing values
df = df.dropna(subset=["Name", "Age", "Salary"])

# Remove invalid records
df = df[(df["Age"] >= 18) & (df["Salary"] >= 0)]

# Transform data
df["Name"] = df["Name"].str.title()
df["Department"] = df["Department"].fillna("Unknown").str.title()
df["Salary Category"] = df["Salary"].apply(
    lambda x: "High" if x >= 40000 else "Low"
)

# Calculate summary
print("\nSummary Report")
print("Total Records:", len(df))
print("Average Age:", df["Age"].mean())
print("Average Salary:", df["Salary"].mean())

# Export cleaned dataset
df.to_csv("cleaned_dataset.csv", index=False)

print("\nCleaned Data:")
print(df)
print("\nCleaned dataset exported successfully!")