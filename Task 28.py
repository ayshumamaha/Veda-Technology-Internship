from flask import Flask, request, jsonify
import sqlite3

app = Flask(__name__)

# Create database
def connect():
    return sqlite3.connect("records.db")


with connect() as db:
    db.execute("""
        CREATE TABLE IF NOT EXISTS records (
            id INTEGER PRIMARY KEY AUTOINCREMENT,
            name TEXT,
            description TEXT
        )
    """)


# Home page
@app.route("/")
def home():
    return "Python REST API is Running!"


# CREATE - Add record
@app.route("/records", methods=["POST"])
def add_record():
    data = request.get_json()

    if not isinstance(data, dict) or not isinstance(data.get("name"), str) or not data["name"].strip():
        return jsonify({"error": "Valid name is required"}), 400

    description = data.get("description", "")

    if not isinstance(description, str):
        return jsonify({"error": "Description must be text"}), 400

    with connect() as db:
        cursor = db.execute(
            "INSERT INTO records (name, description) VALUES (?, ?)",
            (data["name"].strip(), description)
        )

    return jsonify({"message": "Record added", "id": cursor.lastrowid}), 201


# READ - Get all records
@app.route("/records", methods=["GET"])
def get_records():
    with connect() as db:
        rows = db.execute("SELECT * FROM records").fetchall()

    return jsonify([
        {"id": r[0], "name": r[1], "description": r[2]}
        for r in rows
    ])


# UPDATE - Update record
@app.route("/records/<int:id>", methods=["PUT"])
def update_record(id):
    data = request.get_json()

    if not isinstance(data, dict) or not isinstance(data.get("name"), str) or not data["name"].strip():
        return jsonify({"error": "Valid name is required"}), 400

    description = data.get("description", "")

    if not isinstance(description, str):
        return jsonify({"error": "Description must be text"}), 400

    with connect() as db:
        cursor = db.execute(
            "UPDATE records SET name=?, description=? WHERE id=?",
            (data["name"].strip(), description, id)
        )

    if cursor.rowcount == 0:
        return jsonify({"error": "Record not found"}), 404

    return jsonify({"message": "Record updated successfully"})


# DELETE - Remove record
@app.route("/records/<int:id>", methods=["DELETE"])
def delete_record(id):
    with connect() as db:
        cursor = db.execute(
            "DELETE FROM records WHERE id=?", (id,)
        )

    if cursor.rowcount == 0:
        return jsonify({"error": "Record not found"}), 404

    return jsonify({"message": "Record deleted successfully"})


# Run API
if __name__ == "__main__":
    print("PYTHON REST API STARTED")
    app.run(host="127.0.0.1", port=5000)